"""Regenerate the compiled Planckian xy table; never run on the frame path.

Usage: python scripts/generate-light-temperature.py CIE_xyz_1931_2deg.csv
Input: https://files.cie.co.at/CIE_xyz_1931_2deg.csv
CIE 2019, DOI 10.25039/CIE.DS.xvudnb9b, CC BY-SA 4.0.
The generated data retain that attribution and licence separately from code.
"""
import csv
import hashlib
import math
from pathlib import Path
import sys

data = Path(sys.argv[1]).read_bytes()
assert hashlib.sha256(data).hexdigest() == "fa663e3535a7e0763a745993a1f0a192eb0275ac46ad2d1befd7626841e713c1"
observer = [tuple(map(float, row)) for row in csv.reader(data.decode().splitlines())]
rows = []
for kelvin in range(1000, 40001, 100):
    xyz = [0.0, 0.0, 0.0]
    for wavelength, x, y, z in observer:
        wavelength *= 1e-9
        # Planck's second radiation constant h*c/k; common power cancels in xy.
        power = wavelength ** -5 / math.expm1(0.014387768775039337 / (wavelength * kelvin))
        for i, matching in enumerate((x, y, z)):
            xyz[i] += power * matching
    total = sum(xyz)
    rows.append(f"    {{{xyz[0] / total:.10f}F, {xyz[1] / total:.10f}F}}, // {kelvin} K")
header = """// Generated by scripts/generate-light-temperature.py. Planck spectra integrated
// at 1 nm against CIE 2019, Colour-matching functions of CIE 1931 standard
// colorimetric observer, DOI: https://doi.org/10.25039/CIE.DS.xvudnb9b
// Derived data: CC BY-SA 4.0, https://creativecommons.org/licenses/by-sa/4.0/
// Changes: spectral integration and xy normalisation, 1000..40000 K in 100 K steps.
"""
target = Path(__file__).resolve().parents[1] / "engine/scene/src/light_temperature_xy.inc"
target.write_text(header + "\n".join(rows) + "\n", encoding="utf-8")
