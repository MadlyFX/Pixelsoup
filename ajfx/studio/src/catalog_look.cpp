#include "catalog_parts.hpp"

namespace ajfx::studio {

using namespace catalog_controls;

// Look: how they are drawn, and the light they give the scene.
void add_look_blocks(std::vector<BlockDef>& blocks) {
    blocks.push_back(BlockDef{
        .kind = BlockKind::Appearance,
        .title = "Appearance",
        .description = "How each particle is drawn.",
        .category = Category::Look,
        .controls =
            {choice_control("material", "Material", "glow",
                            {{"glow", "Glow"},
                             {"smoke", "Smoke", in_particles},
                             {"solid", "Solid", in_particles},
                             {"model", "Model"},
                             {"trail", "Trail", in_particles}},
                            "How particles are drawn."),
             when(choice_control("texture", "Texture", "dot",
                                 {{"dot", "Soft dot"},
                                  {"glow", "Hot glow"},
                                  {"spark", "Spark"},
                                  {"flame", "Flame"},
                                  {"smoke", "Smoke puff"},
                                  {"wisp", "Wisp"},
                                  {"star", "Star"},
                                  {"ring", "Ring"},
                                  {"file", "From a file"}},
                                 "The picture on each particle."),
                  "material", {"model"}, true),
             when(file_control("texture_file", "Picture", FileKind::Image,
                               "PNG, JPEG, TGA or BMP."),
                  "texture", {"file"}),
             when(number_control("columns", "Frames across", 1.0F, 1.0F, 16.0F, "", 0,
                                 "Flipbook frames across.",
                                 1.0F, 64.0F),
                  "texture", {"file"}),
             when(number_control("rows", "Frames down", 1.0F, 1.0F, 16.0F, "", 0,
                                 "Flipbook frames down.", 1.0F, 64.0F),
                  "texture", {"file"}),
             when(choice_control("mesh", "Model", "slab",
                                 {{"slab", "Slab"}, {"shard", "Shard"}, {"rock", "Rock"}, {"cube", "Cube"},
                                  {"file", "From a file"}},
                                 "Shape of each piece."),
                  "material", {"model"}),
             when(file_control("mesh_file", "Model", FileKind::Model,
                               "OBJ, glTF or GLB, fitted to 1 m."),
                  "mesh", {"file"}),
             when(choice_control("facing", "Facing", "camera",
                                 {{"camera", "Face camera"}, {"motion", "Stretch along motion"}},
                                 "Stretch makes streaks."),
                  "material", {"model", "trail"}, true),
             when(number_control("stretch", "Stretch", 0.04F, 0.0F, 0.3F, "s", 3,
                                 "Streak length, in seconds of travel."),
                  "facing", {"motion"}),
             particles_only(when(toggle_control("spin", "Random spin", false,
                                                "A random angle for each."),
                                 "material", {"model", "trail"}, true)),
             detail(when(number_control("soft", "Soft edges", 0.15F, 0.0F, 1.0F, "m", 2,
                                        "Fades particles at the floor and objects."),
                         "material", {"model"}, true)),
             detail(when(toggle_control("sort", "Depth sort", true,
                                        "Back to front. Glow never needs it."),
                         "material", {"smoke", "solid"})),
             detail(when(toggle_control("blend", "Smooth animation", true,
                                        "Cross-fades flipbook frames."),
                         "texture", {"flame", "smoke", "file"})),
             when(seed_control(), "spin", {"on"}),
             // What the host multiplies the layer by as it draws it. They
             // are here to be published: an operator tints, dims, fades or
             // scales a placement, baked layers included, since a cache
             // never sees them.
             detail(publishable_at_playback(color_control(
                 "tint", "Tint", color(1.0F, 1.0F, 1.0F),
                 "Multiplies each particle's colour."))),
             detail(publishable_at_playback(number_control(
                 "brightness", "Brightness", 1.0F, 0.0F, 4.0F, "x", 2,
                 "Multiplies each particle's brightness.",
                 0.0F, 64.0F))),
             detail(publishable_at_playback(number_control(
                 "opacity", "Opacity", 1.0F, 0.0F, 1.0F, "", 2,
                 "Multiplies each particle's opacity.",
                 0.0F, 1.0F))),
             detail(publishable_at_playback(number_control(
                 "size_scale", "Size scale", 1.0F, 0.0F, 4.0F, "x", 2,
                 "Multiplies the drawn size.",
                 0.0F, 64.0F)))},
        .keywords = "material texture sprite render look blend mesh ribbon trail additive tint opacity",
        .unique = true,
        .detachable = false,
    });
    blocks.push_back(BlockDef{
        .kind = BlockKind::Color,
        .title = "Color",
        .description = "Colour and brightness, and how they age.",
        .category = Category::Look,
        .controls =
            {publishable(color_control("color", "Color", color(1.0F, 0.55F, 0.2F), "The starting colour.")),
             range_control("brightness", "Brightness", 1.0F, 1.0F, 0.0F, 20.0F, "x", 1,
                           "Above 1, particles bloom."),
             number_control("opacity", "Opacity", 1.0F, 0.0F, 1.0F, "", 2, "How solid.", 0.0F, 1.0F),
             choice_control("over_life", "As it ages", "constant",
                            {{"constant", "Stays"},
                             {"fire", "Burns out"},
                             {"cool", "Cools"},
                             {"darken", "Darkens"},
                             {"shift", "Shifts"}},
                            "Burns out: white, yellow, orange, ember."),
             when(color_control("end_color", "Becomes", color(0.35F, 0.1F, 0.8F), "The colour at the end."),
                  "over_life", {"shift"}),
             detail(toggle_control("mix", "Two colors", false, "Each picks a colour between two.")),
             detail(when(color_control("second", "Second color", color(1.0F, 0.8F, 0.35F),
                                       "The other colour."),
                         "mix", {"on"})),
             seed_control()},
        .keywords = "colour tint hue brightness emissive gradient over life hdr",
        .unique = true,
    });
    blocks.push_back(BlockDef{
        .kind = BlockKind::Size,
        .title = "Size",
        .description = "How big particles are, and how they grow.",
        .category = Category::Look,
        .controls = {publishable(range_control("size", "Size", 0.05F, 0.1F, 0.0F, 2.0F, "m", 3,
                                   "Each particle's size, between the two.")),
                     particles_only(choice_control("over_life", "As it ages", "constant",
                                    {{"constant", "Stays"},
                                     {"grow", "Grows"},
                                     {"shrink", "Shrinks"},
                                     {"pop", "Pops"},
                                     {"swell", "Swells"}},
                                    "How size changes over life.")),
                     particles_only(when(number_control("change", "Grows to", 3.0F, 1.0F, 10.0F, "x", 1,
                                         "The end size, as a multiple.", 1.0F, 1000.0F),
                          "over_life", {"grow", "swell"})),
                     seed_control()},
        .keywords = "scale scale over life grow shrink big small",
        .unique = true,
    });
    blocks.push_back(BlockDef{
        .kind = BlockKind::Spin,
        .title = "Spin",
        .description = "Turns each particle's picture.",
        .category = Category::Look,
        .controls = {range_control("speed", "Speed", 30.0F, 120.0F, 0.0F, 720.0F, "deg/s", 0,
                                   "Turn speed, between the two."),
                     detail(toggle_control("both_ways", "Both ways", true,
                                           "Half turn each way.")),
                     detail(number_control("slows", "Slows", 0.5F, 0.0F, 5.0F, "", 2,
                                           "Spin lost per second.")),
                     seed_control()},
        .keywords = "rotate rotation twist turn roll angular",
        .unique = true,
        .layers = in_particles,
        .only_in = "Bodies tumble on their own.",
    });
    blocks.push_back(BlockDef{
        .kind = BlockKind::Fade,
        .title = "Fade",
        .description = "Fades particles in and out.",
        .category = Category::Look,
        .controls = {number_control("in", "Fade in", 10.0F, 0.0F, 50.0F, "% of life", 0, "", 0.0F, 100.0F),
                     number_control("out", "Fade out", 40.0F, 0.0F, 100.0F, "% of life", 0, "", 0.0F, 100.0F)},
        .keywords = "alpha opacity transparency dissolve",
        .unique = true,
    });
    // Hot sparks, embers, a fragment fresh from a blast: a glow on top of the
    // colour that cools with age, red to orange to white and back to dark.
    ControlDef heat_on = choice_control("what", "On", "all", {{"all", "Everything"}, {"pieces", "Broken pieces"}},
                                        "Broken pieces glow; the whole stays cold.");
    heat_on.layers = in_rigid;
    blocks.push_back(BlockDef{
        .kind = BlockKind::Heat,
        .title = "Glows hot",
        .description = "Glows hot, then cools.",
        .category = Category::Look,
        .controls = {number_control("start", "How hot", 1.0F, 0.0F, 3.0F, "", 2, "Above 1 is white hot.", 0.0F,
                                    1.0e3F),
                     number_control("half_life", "Cools by half in", 0.5F, 0.05F, 5.0F, "s", 2, "Seconds to halve.",
                                    0.01F, 1.0e3F),
                     detail(number_control("glow", "Glow", 4.0F, 0.0F, 20.0F, "", 1, "How bright the heat shines.",
                                           0.0F, 1.0e3F)),
                     std::move(heat_on)},
        .keywords = "heat hot glow cool ember molten fire burning incandescent",
        .unique = true,
    });


    blocks.push_back(BlockDef{
        .kind = BlockKind::Light,
        .title = "Cast light",
        .description = "Particles light the scene.",
        .category = Category::Light,
        .controls = {number_control("count", "Lights", 6.0F, 1.0F, 64.0F, "", 0,
                                    "The most lights at once.",
                                    1.0F, 64.0F),
                     range_control("intensity", "Intensity", 1.5F, 2.5F, 0.0F, 20.0F, "", 1,
                                   "Brightness, between the two."),
                     range_control("reach", "Reach", 1.2F, 2.0F, 0.05F, 10.0F, "m", 2,
                                   "How far each light carries, between the two."),
                     detail(choice_control("over_life", "Over its life", "fade",
                                           {{"steady", "Steady"},
                                            {"fade", "Fades in and out"},
                                            {"flare", "Flares, then fades"},
                                            {"out", "Fades out"}},
                                           "Brightness over life.")),
                     detail(choice_control("color_mode", "Light color", "particle",
                                           {{"particle", "The particle's"}, {"own", "Its own"}, {"shift", "Shifts"}},
                                           "Follow the particle, or its own colour.")),
                     detail(when(color_control("light_color", "Color", color(1.0F, 0.6F, 0.3F),
                                               "The light's colour."),
                                 "color_mode", {"own", "shift"})),
                     detail(when(color_control("end_color", "Becomes", color(0.8F, 0.2F, 0.05F),
                                               "The colour at the end of life."),
                                 "color_mode", {"shift"}))},
        .keywords = "illuminate glow point light lighting",
        .unique = true,
        .detachable = false,
    });
}

} // namespace ajfx::studio
